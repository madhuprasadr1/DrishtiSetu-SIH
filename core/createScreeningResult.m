function result = createScreeningResult(imageInput, patientInfo, eyeSelection)
%CREATESCREENINGRESULT Canonical factory function for DrishtiSetu screening result.
%   RESULT = createScreeningResult(IMAGEINPUT, PATIENTINFO, EYESELECTION)
%   initializes the standardized 14-field result structure that feeds the
%   UI, clinical report generator, database persistence, and audit log.

if nargin < 2 || isempty(patientInfo)
    patientInfo = struct('pseudoID', ['P-' char(matlab.lang.makeValidName(datestr(now, 'yymmddHHMMSS')))], ...
        'age', NaN, 'gender', 'Unspecified', 'diabetesYears', NaN);
end
if nargin < 3 || isempty(eyeSelection)
    eyeSelection = 'OD'; % Default Right Eye
end
if isstruct(eyeSelection)
    eyeSelection = 'OD';
end

timestampStr = datestr(now, 'yyyy-mm-dd HH:MM:SS');
caseIDStr = ['DS-' datestr(now, 'yyyymmdd') '-' upper(dec2hex(randi([16^3, 16^4-1]), 4))];

result = struct();
result.status = 'INITIALIZED';

% 1. Case Identification
result.caseID = caseIDStr;

% 2. Patient Demographics & Context (Pseudonymous)
result.patient = patientInfo;

% 3. Examined Eye (OD / OS)
result.eye = char(eyeSelection);

% 4. Image Acquisition Metadata
result.acquisition = struct( ...
    'timestamp', timestampStr, ...
    'imagePath', '', ...
    'cameraID', 'Field-Portable-PHC-1', ...
    'originalImage', []);

% 5. Quality Assessment
result.quality = struct( ...
    'qualityScore', NaN, ...
    'qualityClass', 'UNKNOWN', ... % 'GOOD', 'BORDERLINE', 'BAD'
    'isEnhanced', false, ...
    'failureReasons', {{}}, ...
    'recaptureAdvice', {{}}, ...
    'features', struct(), ...
    'fovMask', [], ...
    'fovInfo', struct());

% 6. Preprocessing
result.preprocessing = struct( ...
    'processedImage', [], ...
    'modelInputImage', [], ...
    'cropBBox', [], ...
    'targetSize', [448, 448]);

% 7. Retinal Anatomy Analysis
result.anatomy = struct( ...
    'retinalMask', [], ...
    'opticDiscMask', [], ...
    'opticDiscCenter', [NaN, NaN], ...
    'opticDiscConfidence', 0, ...
    'foveaLocation', [NaN, NaN], ...
    'foveaConfidence', 0, ...
    'vesselMask', [], ...
    'vesselSkeleton', [], ...
    'vesselDensity', NaN, ...
    'quadrantVesselDensity', zeros(1, 4));

% 8. Lesion Analysis & Candidate Evidence
result.lesions = struct( ...
    'microaneurysms', struct('count', 0, 'mask', [], 'centroids', zeros(0, 2), 'quadrantCounts', zeros(1, 4)), ...
    'haemorrhages', struct('count', 0, 'mask', [], 'centroids', zeros(0, 2), 'quadrantCounts', zeros(1, 4)), ...
    'hardExudates', struct('count', 0, 'mask', [], 'centroids', zeros(0, 2), 'quadrantCounts', zeros(1, 4)), ...
    'softExudates', struct('count', 0, 'mask', [], 'centroids', zeros(0, 2), 'quadrantCounts', zeros(1, 4)), ...
    'totalCandidateCount', 0, ...
    'evidenceSource', 'None', ...
    'evidenceOverlay', []);

% 8b. Quantitative Measurement Engine (M06)
result.measurements = struct( ...
    'version', 'DS-MEASUREMENT-1.0', ...
    'scaleCalibration', struct('hasScale', false, 'umPerPixel', NaN), ...
    'unitArea', 'pixels', ...
    'unitDiameter', 'pixels', ...
    'totalLesionCount', 0, ...
    'totalLesionArea', 0, ...
    'macularThreatCount', 0, ...
    'quadrantCounts', struct('ST', 0, 'IT', 0, 'SN', 0, 'IN', 0), ...
    'microaneurysms', struct('count', 0, 'totalArea', 0, 'details', []), ...
    'haemorrhages', struct('count', 0, 'totalArea', 0, 'details', []), ...
    'hardExudates', struct('count', 0, 'totalArea', 0, 'details', []), ...
    'softExudates', struct('count', 0, 'totalArea', 0, 'details', []));

% 9. Diabetic Retinopathy Grading
result.dr = struct( ...
    'drGrade', NaN, ...             % 0, 1, 2, 3, 4
    'drLabel', 'Unclassified', ...  % e.g. 'Moderate NPDR (Level 2)'
    'referable', false, ...         % true if Level >= 2
    'rawProbabilities', zeros(5, 1), ...
    'calibratedProbabilities', zeros(5, 1), ...
    'calibratedReferableProbability', 0, ...
    'temperature', 1.0, ...
    'calibrationApplied', false, ...
    'modelCheckpoint', 'None');

% 10. Safety & Uncertainty Gating
result.safety = struct( ...
    'confidenceScore', 0, ...
    'uncertaintyScore', 0, ...
    'oodFlag', false, ...
    'oodDetails', struct('score', 0, 'reason', ''), ...
    'safetyStatus', 'INITIALIZING', ... % 'SAFE_FOR_AI_ASSISTED_RESULT', 'HUMAN_REVIEW_REQUIRED', 'RECAPTURE_REQUIRED'
    'reviewRequired', true, ...
    'reasonCodes', {{}}, ...
    'warnings', {{}});

% 11. Explainability & Visual Evidence
result.explainability = struct( ...
    'gradCAMHeatmap', [], ...
    'gradCAMOverlay', [], ...
    'lesionOverlay', [], ...
    'vesselOverlay', [], ...
    'compositeExplanation', [], ...
    'spatialAgreement', 'Not assessed', ...
    'explanationNarrative', '');

% 12. Human-in-the-Loop Review
result.review = struct( ...
    'status', 'PENDING', ... % 'PENDING', 'ACCEPTED', 'MODIFIED', 'REJECTED'
    'reviewerID', '', ...
    'reviewTimestamp', '', ...
    'originalAIGrade', NaN, ...
    'finalDeterminedGrade', NaN, ...
    'clinicianNotes', '', ...
    'modificationReason', '');

% 13. Advanced Estimated 3D Retinal Visualization (M13 - Decoupled)
result.advanced3D = struct( ...
    'status', 'NOT_RUN', ...
    'mode', 'FUNDUS_ESTIMATED', ...
    'depthInfo', struct(), ...
    'rendered3DImage', [], ...
    'elevationSpan', 0, ...
    'unit', 'microns (estimated)', ...
    'errorMessage', '');

% 14. Clinical Screening Report
result.report = struct( ...
    'reportGenerated', false, ...
    'reportPDFPath', '', ...
    'reportPNGPath', '', ...
    'reportTextPath', '', ...
    'summaryText', '');

% 15. Audit & Provenance
result.audit = struct( ...
    'systemName', 'DrishtiSetu', ...
    'systemVersion', '1.0.0-MVP', ...
    'timestamp', timestampStr, ...
    'inferenceDurationSeconds', 0, ...
    'executionEnvironment', 'CPU', ...
    'regulatoryNotice', 'Investigational Screening Prototype. Clinician verification mandatory.');

% Assign input image if provided
if nargin >= 1 && ~isempty(imageInput)
    if ischar(imageInput) || isstring(imageInput)
        result.acquisition.imagePath = char(imageInput);
    elseif isnumeric(imageInput) || islogical(imageInput)
        result.acquisition.originalImage = imageInput;
    end
end
end
